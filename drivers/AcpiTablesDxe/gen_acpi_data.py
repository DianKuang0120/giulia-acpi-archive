#!/usr/bin/env python3
#
# Regenerate AcpiTablesData.c from the .aml files that AcpiTables.inf lists.
#
# Usage:  ./gen_acpi_data.py [Silicium-ACPI root] [output file]
#
# The output is a plain C file with one array per table, included by
# AcpiTablesDxe.c.  Run it after rebuilding any table with iasl.
#
import re
import sys
from pathlib import Path

ACPI_ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[5] / "Silicium-ACPI"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent / "AcpiTablesData.c"

INF = ACPI_ROOT / "Platforms/OnePlus/giulia/AcpiTables.inf"

# INF table name -> C symbol
SYMBOLS = {
    "DSDT": "gAcpiDsdt",
    "APIC": "gAcpiApic",
    "FACP": "gAcpiFadt",
    "GTDT": "gAcpiGtdt",
    "MCFG": "gAcpiMcfg",
    "PPTT": "gAcpiPptt",
    "DBG2": "gAcpiDbg2",
    "SPCR": "gAcpiSpcr",
}


def main():
    tables = []
    for line in INF.read_text().splitlines():
        m = re.match(r"\s*ASL\|(.*)", line)
        if not m:
            continue
        rel = m.group(1).strip()
        path = INF.parent / rel
        if not path.is_file():
            # EDK2 resolves [Binaries] against every package in the workspace,
            # so Silicon/... is rooted at the Silicium-ACPI tree, not here.
            path = ACPI_ROOT / rel
        blob = path.read_bytes()
        name = blob[0:4].decode("ascii")
        if name == "SSDT":
            continue  # placeholder SSDE table, not used on this platform
        tables.append((name, blob))

    out = ["// Auto-generated by gen_acpi_data.py from Silicium-ACPI, do not edit.", ""]
    for name, blob in tables:
        symbol = SYMBOLS[name]
        out.append(f"// {name} ({len(blob)} bytes)")
        out.append(f"UINT8 {symbol}[] = {{")
        for i in range(0, len(blob), 12):
            chunk = blob[i:i + 12]
            out.append("  " + " ".join(f"0x{b:02X}," for b in chunk))
        out.append("};")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"{OUT}: {len(tables)} tables, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
